'use strict';
const assert=require('node:assert/strict');
const {groups,extract}=require('../radar-view.js');
const base={r5:.02,rs5:.01,rank_move:.21,attention:1.4,stage:'普通',breadth:{breadth_change:.2},flags:[]};
const a={...base,code:'a',name:'甲',flags:['量价前兆','排名跃升','关注度异动','扩散增强']};
const b={...base,code:'b',name:'乙',r5:-.06,rs5:-.08,attention:2,stage:'退潮',breadth:{breadth_change:-.3},flags:['关注度异动','放量下跌','扩散收窄']};
const c={...base,code:'c',name:'丙',rs5:.07,attention:1.1,flags:[],breadth:null};
const d={version:'industry-radar-v1.1',asof:'20261125',levels:{L1:[a],L2:[a,b,c]}};
const h='<!doctype html><script type="application/json" id="data">'+JSON.stringify(d)+'</script><script>throw Error("must not execute")</script>';
assert.deepEqual(extract(h,'20261125'),d);
assert.throws(()=>extract(h,'20261126'));
assert.throws(()=>extract('<!doctype html><script>alert(1)</script>','20261125'));
assert.deepEqual(groups([a,b,c],'discover').map(g=>g.rows.map(x=>x.code)),[['a'],['a'],['b','a']]);
assert.deepEqual(groups([a,b,c],'strong')[0].rows.map(x=>x.code),['c','a','b']);
assert.deepEqual(groups([a,b,c],'breadth').map(g=>g.rows.map(x=>x.code)),[['a'],['b']]);
assert.deepEqual(groups([a,b,c],'risk')[0].rows.map(x=>x.code),['b']);
assert.equal(groups([c],'discover')[0].rows.length,0);
assert.equal(groups([a,b,c],'all')[0].rows.length,3);
assert.deepEqual([a,b,c].map(x=>x.code),['a','b','c']);
console.log('Radar view: authenticated snapshot parsing, five views, missing values and empty signal tests passed');
